/**
 * Generates `claims.json` — the single source of truth for every countable
 * claim the project publishes (website copy, README badges, docs).
 *
 * Why this exists
 * ---------------
 * The site claimed "80+ coding agents", "45+ credential shapes" and "69 tools
 * across 6 profiles". Reality was 52 agents, 8 credential rule families and
 * 112 tools across 7 profiles. Nothing caught the drift because each number
 * was hand-typed into prose in five different files.
 *
 * So: count them from the code, write them to one JSON file, and let the
 * website and the tests read that file. `test/marketing_claims.test.ts`
 * re-derives every value from `src/` and fails if `claims.json` disagrees,
 * which means the number can never drift again without a test failing.
 *
 * Usage:
 *   bun run scripts/generate-claims.ts
 *   bun run scripts/generate-claims.ts --check   # fail if stale
 */
import { AGENT_REGISTRY } from "../src/agents/registry.ts";
import { PROFILE_TOOL_DEFINITIONS } from "../src/orchestrator/profiles.ts";
import { PROVIDER_DEFINITIONS } from "../src/migrator/detect.ts";
import { SECRET_RULES } from "../src/secrets.ts";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const OUT = join(ROOT, "claims.json");

/** Every MCP tool name registered in src/mcp.ts. */
function registeredMcpTools(): string[] {
  const src = readFileSync(join(ROOT, "src/mcp.ts"), "utf8");
  return [
    ...new Set([...src.matchAll(/name:\s*"([a-z0-9_]+)"/g)].map((m) => m[1]!)),
  ]
    .filter((n) => n !== "musememory")
    .sort();
}

function countTestFiles(): number {
  // Bun's own count is authoritative, and it includes a few `*.test.ts`
  // files that live next to the code in `src/` — so this is a floor, not
  // the real number. The real number comes from the JUnit report.
  let n = 0;
  for (const dir of ["test", "src"]) {
    const walk = (d: string) => {
      for (const entry of readdirSync(d)) {
        const full = join(d, entry);
        if (statSync(full).isDirectory()) walk(full);
        else if (entry.endsWith(".test.ts")) n++;
      }
    };
    walk(join(ROOT, dir));
  }
  return n;
}

/**
 * Runs the suite and reads the totals from the JUnit report.
 * This is the only place that knows how many assertions the suite makes.
 */
async function runSuite(): Promise<{ tests: number; assertions: number; files: number }> {
  const outfile = "/tmp/claims-junit.xml";
  const proc = Bun.spawn(
    ["bun", "test", "--reporter=junit", `--reporter-outfile=${outfile}`],
    { cwd: ROOT, stdout: "pipe", stderr: "pipe" },
  );
  await proc.exited;
  const xml = readFileSync(outfile, "utf8");
  const root = xml.match(/<testsuites\b[^>]*>/)?.[0] ?? "";
  const num = (attr: string) => Number(root.match(new RegExp(`${attr}="([0-9]+)"`))?.[1] ?? 0);
  const files = new Set([...xml.matchAll(/<testsuite\b[^>]*file="([^"]+)"/g)].map((m) => m[1]!)).size;
  return { tests: num("tests"), assertions: num("assertions"), files };
}

async function build() {
  const tools = registeredMcpTools();
  const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
  const suite = await runSuite();

  const claims = {
    $comment:
      "Generated by scripts/generate-claims.ts. Do not hand-edit: test/marketing_claims.test.ts re-derives every value from src/ and fails on drift.",
    version: pkg.version,
    mcpTools: tools.length,
    mcpProfiles: Object.keys(PROFILE_TOOL_DEFINITIONS).length,
    agentPlatforms: AGENT_REGISTRY.length,
    migratorProviders: PROVIDER_DEFINITIONS.length,
    credentialRuleFamilies: SECRET_RULES.length,
    backgroundDaemons: 0,
    tests: {
      count: suite.tests,
      assertions: suite.assertions,
      files: suite.files,
    },
  };

  return { claims, tools };
}

const { claims, tools } = await build();
const serialized = JSON.stringify(claims, null, 2) + "\n";
// The tool list is large and changes often; it lives in the generated
// `docs/mcp-tool-matrix.json` instead, so claims.json stays small and stable.
const toolMatrix = {
  $comment: "Generated by scripts/generate-claims.ts — the authoritative MCP tool list.",
  count: tools.length,
  tools,
};
const toolMatrixPath = join(ROOT, "docs/mcp-tool-matrix.json");

const checkOnly = process.argv.includes("--check");

if (checkOnly) {
  let stale = false;
  const current = readFileSync(OUT, "utf8");
  const currentClaims = JSON.parse(current) as typeof claims;

  // The structural counts are derived from a stable source: if one of them
  // moved, the source changed and the manifest must be regenerated.
  for (const key of [
    "version",
    "mcpTools",
    "mcpProfiles",
    "agentPlatforms",
    "migratorProviders",
    "credentialRuleFamilies",
    "backgroundDaemons",
  ] as const) {
    if (currentClaims[key] !== claims[key]) {
      stale = true;
      console.error(
        `STALE: claims.json — ${key} is ${JSON.stringify(currentClaims[key])}, source says ${JSON.stringify(claims[key])}`,
      );
    }
  }

  // The test count is different: the suite grows every time a test is
  // added, so an exact match would fail CI on every unrelated test commit.
  // The failure that actually matters is OVER-claiming — publishing a count
  // higher than the suite contains. Stale-low is merely imprecise, and the
  // release process regenerates the manifest so the published figure is exact
  // at the moment it ships.
  if (currentClaims.tests.count > claims.tests.count) {
    stale = true;
    console.error(
      `STALE: claims.json — claims ${currentClaims.tests.count} tests but the suite contains ${claims.tests.count}`,
    );
  } else if (currentClaims.tests.count < claims.tests.count) {
    console.log(
      `note: claims.json reports ${currentClaims.tests.count} tests; the suite now has ${claims.tests.count}. ` +
        `Run "bun run claims:generate" to publish the exact figure.`,
    );
  }
  if (currentClaims.tests.files > claims.tests.files) {
    stale = true;
    console.error(
      `STALE: claims.json — claims ${currentClaims.tests.files} test files but the suite contains ${claims.tests.files}`,
    );
  }

  // The tool matrix must match exactly: it is a list, not a statistic.
  const currentMatrix = readFileSync(toolMatrixPath, "utf8");
  if (currentMatrix !== JSON.stringify(toolMatrix, null, 2) + "\n") {
    stale = true;
    console.error(`STALE: ${toolMatrixPath}`);
  }

  if (stale) {
    console.error("Run: bun run claims:generate");
    process.exit(1);
  }
  console.log("claims.json and docs/mcp-tool-matrix.json are up to date.");
  process.exit(0);
}

writeFileSync(OUT, serialized);
writeFileSync(toolMatrixPath, JSON.stringify(toolMatrix, null, 2) + "\n");
console.log(serialized);
console.log(`Wrote ${toolMatrixPath} (${tools.length} tools)`);
process.exit(0);
